#ifndef OLED_TASK_H
#define OLED_TASK_H

/**
 ******************************************************************************
 * @file    oled_task.h
 * @brief   OLED显示任务头文件
 * @details 本文件提供了OLED显示任务的入口函数
 *          负责在OLED屏幕上显示系统各种信息
 ******************************************************************************
 */

// ==================== 函数声明 ====================

/**
 * @brief OLED显示任务入口函数
 * @param param 任务参数（未使用）
 * @details 显示内容：
 *          - 页面0：实时数据（时间、温度、湿度、光照）
 *          - 页面1：设备状态（窗帘、风扇、灯光)
 *          - 页面2：目标环境参数（温度、湿度、光照阈值）
 *          - 页面3：保存到 Flash 提示界面
 *          - 右上角显示WiFi连接状态图标
 * @note 每页显示内容根据全局状态变量动态更新
 */
void OLED_Task(void *param);

#endif

