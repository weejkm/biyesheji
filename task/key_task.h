#ifndef KEY_TASK_H
#define KEY_TASK_H

/**
 ******************************************************************************
 * @file    key_task.h
 * @brief   按键和旋转编码器处理任务头文件
 * @details 本文件提供了按键和编码器处理任务的入口函数
 *          负责处理按键事件、编码器旋转、RFID读写、语音控制指令等
 ******************************************************************************
 */

// ==================== 函数声明 ====================

/**
 * @brief 按键和编码器处理任务入口函数
 * @param param 任务参数（未使用）
 * @details 功能说明：
 *          1. KEY1短按：切换OLED显示页面，并设置自动模式状态
 *          2. KEY2短按：
 *             - 在设备状态页和阈值页：切换选择项
 *             - 在保存页：将阈值写入RFID卡
 *          3. KEY3短按：返回主页面
 *          4. KEY3长按：切换在线/离线模式
 *          5. 旋转编码器：
 *             - 阈值页：调整温度、湿度、光照阈值
 *             - 设备状态页：控制窗帘、风扇、灯光
 *             - 其他页面：调整灯光亮度
 *          6. RFID读写：
 *             - 阈值页读取RFID卡中的阈值设置
 *             - 保存页将当前阈值写入RFID卡
 *          7. 语音控制：
 *             - 接收语音模块指令，控制设备
 *             - 支持灯光、风扇、窗帘等控制
 * @note 所有设备控制操作都会实时生效，并更新全局状态变量
 */
void KEY_Task(void *param);

#endif

