#ifndef __ENCODER_H
#define __ENCODER_H

/**
 ******************************************************************************
 * @file    Encoder.h
 * @brief   旋转编码器驱动头文件
 * @details 本文件提供了旋转编码器的初始化和计数读取功能
 *          使用外部中断检测编码器A、B相的边沿变化
 *          编码器连接在PB0（A相）和PB1（B相）
 *          支持正转和反转检测
 ******************************************************************************
 */

#include "stdint.h"

// ==================== 全局变量声明 ====================

/**
 * @brief 编码器计数值
 * @note 正转时增加，反转时减少
 *       调用Encoder_Get函数会返回当前值并清零
 */
extern int16_t Encoder_Count;

// ==================== 函数声明 ====================

/**
 * @brief 初始化编码器驱动
 * @note 配置PB0和PB1为上拉输入，配置外部中断
 *       使用下降沿和上升沿触发中断，检测旋转方向
 */
void Encoder_Init(void);

/**
 * @brief 获取编码器计数值（读取后清零）
 * @return 当前计数值（读取后自动清零）
 * @note 该函数返回当前计数值，并自动将计数器清零
 *       适合用于读取旋转增量
 */
int16_t Encoder_Get(void);

#endif

